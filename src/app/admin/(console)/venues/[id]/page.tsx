import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { ChevronLeft, Download } from "lucide-react";
import QRCode from "qrcode";
import { Suspense, type ReactNode } from "react";
import { Card } from "@/components/ui/Card";
import { GymPasswordCard, VenueForm } from "@/features/venue/components/VenueForms";
import { entryUrl, getAdminVenue, listAdminVenues } from "@/features/venue/queries";
import { shortDate } from "@/features/mypage/components/MySection";
import { DOMAIN_IS_FINAL } from "@/lib/site";
import { requireAdmin } from "@/server/admin-session";

export const metadata: Metadata = { title: "会場の詳細" };

function Block({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section>
      <h2 className="mb-3 text-lg font-bold">{title}</h2>
      <Card className="bg-white">{children}</Card>
    </section>
  );
}

const downloadClass =
  "inline-flex min-h-11 items-center gap-1.5 rounded-full border border-line bg-white px-5 text-sm font-bold hover:border-gray-300";

async function Detail({ params }: { params: PageProps<"/admin/venues/[id]">["params"] }) {
  await requireAdmin();
  const { id } = await params;
  const [venue, all] = await Promise.all([getAdminVenue(id), listAdminVenues()]);
  if (!venue) notFound();
  const regions = [...new Set(all.map((v) => v.region).filter(Boolean))];
  const url = entryUrl(venue.id);
  // Generated by the qrcode library from our own URL, so it is safe to inline.
  const svg = await QRCode.toString(url, { type: "svg", errorCorrectionLevel: "M", margin: 1 });

  return (
    <div className="space-y-8">
      <div>
        <p className="font-display text-sm font-bold text-text-3">{venue.id}</p>
        <h1 className="text-2xl font-bold tracking-tight">{venue.name}</h1>
        {venue.updatedBy && (
          <p className="mt-1 text-sm text-text-3">
            最終更新 {shortDate(venue.updatedAt)}（{venue.updatedBy}）
          </p>
        )}
      </div>

      <Block title="開催内容">
        <VenueForm venue={venue} regions={regions} />
      </Block>

      <Block title="統一 QR コード">
        <div className="flex flex-col gap-6 sm:flex-row sm:items-start">
          <div
            className="w-44 shrink-0 rounded-xl border border-line bg-white p-2 [&_svg]:h-auto [&_svg]:w-full"
            role="img"
            aria-label={`${venue.name} の QR コード`}
            dangerouslySetInnerHTML={{ __html: svg }}
          />
          <div className="min-w-0 space-y-3">
            <p className="text-sm text-text-2">
              1枚の QR で、選手の Division と開催内容に合わせて Tryout か Ranking
              へ自動で案内します。
            </p>
            <p className="font-mono text-sm break-all">{url}</p>
            {!DOMAIN_IS_FINAL && (
              <p className="rounded-xl border border-status-pending/40 bg-status-pending/10 p-3 text-sm text-[#a16207]">
                本番のドメインが決まるまでは仮の URL です。POP
                の印刷は、ドメインが決まってからにしてください。
              </p>
            )}
            <div className="flex flex-wrap gap-2">
              <a href={`/api/admin/venues/${venue.id}/qr`} download className={downloadClass}>
                <Download className="size-4" aria-hidden />
                SVG（印刷用）
              </a>
              <a
                href={`/api/admin/venues/${venue.id}/qr?format=png`}
                download
                className={downloadClass}
              >
                <Download className="size-4" aria-hidden />
                PNG
              </a>
            </div>
          </div>
        </div>
      </Block>

      <Block title="店舗パスワード">
        <GymPasswordCard id={venue.id} hasPassword={venue.hasPassword} />
      </Block>
    </div>
  );
}

export default function AdminVenuePage(props: PageProps<"/admin/venues/[id]">) {
  return (
    <>
      <Link
        href="/admin/venues"
        className="mb-4 inline-flex min-h-11 items-center gap-1 text-sm font-bold text-text-2 hover:text-text"
      >
        <ChevronLeft className="size-4" aria-hidden />
        会場一覧へ
      </Link>
      <Suspense fallback={<div className="h-96 rounded-2xl bg-white" aria-busy="true" />}>
        <Detail params={props.params} />
      </Suspense>
    </>
  );
}
