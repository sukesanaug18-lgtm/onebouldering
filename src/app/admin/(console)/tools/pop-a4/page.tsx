import type { Metadata } from "next";
import Image from "next/image";
import Link from "next/link";
import QRCode from "qrcode";
import { Suspense } from "react";
import { GYMS } from "@/content/gyms";
import { POP_FOOTER, POP_POINTS } from "@/content/pop";
import { popPages, POP_REGIONS, type PopPage } from "@/domain/pop";
import { PrintButton } from "@/features/pop/components/PrintButton";
import { RankingLogo } from "@/components/ui/RankingLogo";
import { PageSkeleton } from "@/features/tnfc/components/Parts";
import { listAdminVenues } from "@/features/venue/queries";
import { cn } from "@/lib/cn";
import { CURRENT_SEASON_ID, seasonLabel } from "@/lib/season";
import { DOMAIN_IS_FINAL, SITE_URL } from "@/lib/site";
import { requireAdmin } from "@/server/admin-session";

export const metadata: Metadata = { title: "A4 POP" };

// A4 schedule POP for gyms, one page per region, built from the venue list (Ranking gyms and
// their periods). Printed from the browser; the office menu and controls are hidden in print.

// Row sizes by the number of gyms, so the list always fits on one A4 sheet.
const SIZES = [
  { upTo: 4, row: "py-[3mm]", logo: "h-[22mm] w-[44mm]", name: "text-[17pt]" },
  { upTo: 6, row: "py-[2mm]", logo: "h-[17mm] w-[36mm]", name: "text-[15pt]" },
  { upTo: 9, row: "py-[1.5mm]", logo: "h-[12mm] w-[28mm]", name: "text-[13pt]" },
  { upTo: Infinity, row: "py-[1mm]", logo: "h-[9mm] w-[22mm]", name: "text-[11pt]" },
];

function PopSheet({ page, qr, url }: { page: PopPage; qr: string; url: string }) {
  const size = SIZES.find((x) => page.venues.length <= x.upTo)!;
  return (
    <article className="pop-page mx-auto flex h-[297mm] w-[210mm] shrink-0 flex-col overflow-hidden bg-white text-[#1d1d1f] shadow-sm print:shadow-none">
      <header className="bg-[#1d1d1f] px-[14mm] pt-[10mm] pb-[7mm] text-white">
        {/* Ranking official logo (design rule: always on Ranking material; white on dark). */}
        <div className="flex items-end gap-[4mm]">
          <RankingLogo tone="dark" className="h-[16mm]" />
          <p className="pb-[1mm] font-display text-[11pt] font-bold tracking-[0.2em] text-[#FF8C3F]">
            SEASON {seasonLabel(CURRENT_SEASON_ID)}
          </p>
        </div>
        <h2 className="mt-[2mm] text-[28pt] leading-tight font-bold tracking-tight">
          {page.region}エリア 開催スケジュール
        </h2>
        <p className="mt-[2mm] text-[11pt] text-white/80">
          エリアのジムを回って、地域ランキング1位と全国総合ランキング入りを目指そう。
        </p>
      </header>

      <ul className="min-h-0 flex-1 px-[14mm] py-[5mm]">
        {page.venues.map((v) => (
          <li
            key={v.id}
            className={cn(
              "flex items-center gap-[6mm] border-b border-[#e5e7eb] last:border-b-0",
              size.row,
            )}
          >
            <span
              className={cn(
                "flex shrink-0 items-center justify-center rounded-[3mm] border border-[#e5e7eb] p-[2mm]",
                size.logo,
                v.logo?.dark ? "bg-[#1d1d1f]" : "bg-white",
              )}
            >
              {v.logo ? (
                <Image
                  src={v.logo.src}
                  alt=""
                  width={240}
                  height={120}
                  loading="eager"
                  className="h-full w-full object-contain"
                />
              ) : (
                <span className="text-center text-[9pt] font-bold">{v.name}</span>
              )}
            </span>
            <span className={cn("min-w-0 flex-1 font-bold", size.name)}>{v.name}</span>
            <span className="shrink-0 rounded-full bg-[#f5f5f7] px-[4mm] py-[1.5mm] text-[12pt] font-bold tabular-nums">
              {v.period}
            </span>
          </li>
        ))}
      </ul>

      <section className="grid grid-cols-2 gap-[3mm] px-[14mm] pb-[5mm]">
        {POP_POINTS.map((p) => (
          <div key={p.title} className="rounded-[3mm] bg-[#f5f5f7] px-[4mm] py-[3mm]">
            <p className="text-[11.5pt] font-bold">{p.title}</p>
            <p className="mt-[1mm] text-[9pt] leading-snug text-[#515154]">{p.body}</p>
          </div>
        ))}
      </section>

      <footer className="flex items-center justify-between gap-[6mm] border-t-[1.5mm] border-[#FF8C3F] px-[14mm] py-[6mm]">
        <div>
          <p className="text-[18pt] font-bold">{POP_FOOTER.lead}</p>
          <p className="mt-[1mm] text-[11pt] text-[#515154]">右の QR コードから公式サイトへ</p>
          <p className="mt-[1mm] font-display text-[10pt] text-[#515154]">
            {url.replace(/^https?:\/\//, "")}
          </p>
          <p className="mt-[2mm] text-[10pt] text-[#515154]">{POP_FOOTER.instagram}</p>
        </div>
        {/* Generated by the qrcode library from our own URL, so it is safe to inline. */}
        <span
          className="block size-[30mm] shrink-0 [&>svg]:h-full [&>svg]:w-full"
          dangerouslySetInnerHTML={{ __html: qr }}
        />
      </footer>
    </article>
  );
}

async function Pop({
  searchParams,
}: {
  searchParams: PageProps<"/admin/tools/pop-a4">["searchParams"];
}) {
  await requireAdmin();
  const sp = await searchParams;
  const regions = popPages(
    (await listAdminVenues()).map((v) => ({
      id: v.id,
      name: v.name,
      region: v.region,
      visible: v.visible,
      hasRanking: v.programs.hasRanking,
      period: v.programs.rankingPeriod,
    })),
    GYMS,
  );
  const selected = regions.find((p) => p.region === sp.region)?.region ?? null;
  const pages = selected ? regions.filter((p) => p.region === selected) : regions;
  const url = `${SITE_URL}/ranking/about`;
  const qr = await QRCode.toString(url, { type: "svg", errorCorrectionLevel: "M", margin: 1 });
  const chip = (active: boolean) =>
    cn(
      "inline-flex min-h-11 items-center rounded-full border px-4 text-sm font-bold whitespace-nowrap",
      active ? "border-text bg-text text-white" : "border-line bg-white hover:border-gray-300",
    );

  return (
    <>
      <div className="space-y-4 print:hidden">
        <nav aria-label="地域" className="-mx-5 overflow-x-auto px-5">
          <ul className="flex min-w-max gap-2">
            <li>
              <Link href="/admin/tools/pop-a4" className={chip(!selected)}>
                全地域（{regions.length}枚）
              </Link>
            </li>
            {regions.map((p) => (
              <li key={p.region}>
                <Link
                  href={`/admin/tools/pop-a4?region=${encodeURIComponent(p.region)}`}
                  className={chip(selected === p.region)}
                >
                  {p.region}（{p.venues.length}）
                </Link>
              </li>
            ))}
          </ul>
        </nav>
        <div className="flex flex-wrap items-center gap-4">
          <PrintButton />
          <p className="text-sm text-text-2">
            印刷の設定で「用紙 A4・余白なし・背景のグラフィック」を選んでください。
          </p>
        </div>
        {!DOMAIN_IS_FINAL && (
          <p className="rounded-xl border border-amber-300 bg-amber-50 p-4 text-sm">
            本番のドメインが決まる前なので、QR コードは仮の URL（{url}
            ）です。配布用の印刷はドメインが決まってからにしてください。
          </p>
        )}
        {regions.length < POP_REGIONS.length && (
          <p className="text-sm text-text-3">
            Ranking
            を開催するジムがない地域は出していません。会場と開催期間は「会場」画面で直せます。
          </p>
        )}
      </div>
      <div className="mt-6 overflow-x-auto rounded-2xl bg-bg-subtle p-4 print:m-0 print:overflow-visible print:rounded-none print:bg-white print:p-0">
        <div className="flex w-max flex-col gap-6 print:block print:w-auto">
          {pages.map((p) => (
            <PopSheet key={p.region} page={p} qr={qr} url={url} />
          ))}
        </div>
      </div>
    </>
  );
}

export default function PopA4Page({ searchParams }: PageProps<"/admin/tools/pop-a4">) {
  return (
    <>
      <div className="print:hidden">
        <h1 className="text-2xl font-bold tracking-tight">A4 POP（開催スケジュール）</h1>
        <p className="mt-2 mb-6 text-sm text-text-2">
          ジムに貼る地域別の開催スケジュールです。「会場」画面の Ranking 開催期間から作ります。
        </p>
      </div>
      <Suspense fallback={<PageSkeleton />}>
        <Pop searchParams={searchParams} />
      </Suspense>
    </>
  );
}
